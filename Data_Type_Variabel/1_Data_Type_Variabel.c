#include <stdio.h>
 int main() {
 int usia = 25;
 float tinggi = 1.75;
 char huruf = 'A';

 printf("Usia: %d\n", usia); // Menampilkan bilangan bulat (usia)
 printf("Tinggi: %.2f\n", tinggi); // Menampilkan bilangan desimal
 printf("Huruf: %c\n", huruf); // Menampilkan karakter (huruf)
 return 0;
}

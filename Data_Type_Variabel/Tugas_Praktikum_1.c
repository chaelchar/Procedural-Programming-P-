#include <stdio.h>
 int main() {
 int usia = 25;
 float tinggi = 1.75;
 char huruf = 'A';
 // Menampilkan nilai variabel
 printf("Usia: %d\n", usia);
 printf("Tinggi: %.2f\n", tinggi);
 printf("Huruf: %c\n", huruf);

//  Tugas
 double phi = 3.14159;
 long long int kilometer = 40100000000;
 printf("Phi: %lf\n",phi);
 printf("kilometer: %lld\n",kilometer);

 return 0;
}
